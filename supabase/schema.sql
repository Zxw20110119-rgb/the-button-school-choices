-- Run this once in the Supabase SQL Editor.
create extension if not exists pgcrypto;

create type public.vote_choice as enum ('PRESS','WALK_AWAY');

create table public.questions (
  id bigint generated by default as identity primary key,
  benefit_text text not null check (char_length(benefit_text) between 10 and 240),
  consequence_text text not null check (char_length(consequence_text) between 10 and 240),
  category text not null check (char_length(category) between 2 and 40),
  press_value text not null default 'Progress',
  walk_value text not null default 'Caution',
  active boolean not null default true,
  version integer not null default 1 check (version > 0),
  real_votes_enabled boolean not null default true,
  optional_test_mode boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.votes (
  id bigint generated always as identity primary key,
  anonymous_user_id text not null check (char_length(anonymous_user_id) between 12 and 80),
  question_id bigint not null references public.questions(id) on delete restrict,
  choice public.vote_choice not null,
  is_test boolean not null default false,
  created_at timestamptz not null default now(),
  constraint one_vote_per_device_question unique (anonymous_user_id, question_id)
);

create table public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create index votes_question_id_idx on public.votes(question_id);
create index votes_anonymous_user_id_idx on public.votes(anonymous_user_id);
create index votes_created_at_idx on public.votes(created_at desc);
create index questions_active_category_idx on public.questions(active,category);

create or replace function public.touch_updated_at() returns trigger language plpgsql as $$
begin new.updated_at=now(); return new; end $$;
create trigger questions_touch_updated_at before update on public.questions for each row execute function public.touch_updated_at();

alter table public.questions enable row level security;
alter table public.votes enable row level security;
alter table public.admin_users enable row level security;

create policy "admins read questions" on public.questions for select to authenticated using (exists(select 1 from public.admin_users a where a.user_id=auth.uid()));
create policy "admins insert questions" on public.questions for insert to authenticated with check (exists(select 1 from public.admin_users a where a.user_id=auth.uid()));
create policy "admins update questions" on public.questions for update to authenticated using (exists(select 1 from public.admin_users a where a.user_id=auth.uid())) with check (exists(select 1 from public.admin_users a where a.user_id=auth.uid()));
create policy "admins read votes" on public.votes for select to authenticated using (exists(select 1 from public.admin_users a where a.user_id=auth.uid()));
create policy "admins see own access" on public.admin_users for select to authenticated using (user_id=auth.uid());

create or replace function public.get_game_questions(question_count integer default 10)
returns table(id bigint,benefit_text text,consequence_text text,category text,press_value text,walk_value text,version integer)
language sql stable security definer set search_path=public
as $$
  with category_pick as (
    select distinct on (q.category) q.id,q.benefit_text,q.consequence_text,q.category,q.press_value,q.walk_value,q.version
    from public.questions q
    where q.active and q.real_votes_enabled and not q.optional_test_mode
    order by q.category,random()
  )
  select * from category_pick order by random() limit greatest(1,least(question_count,10));
$$;

create or replace function public.submit_vote(p_anonymous_user_id text,p_question_id bigint,p_choice public.vote_choice)
returns table(press_votes bigint,walk_votes bigint,total_votes bigint,previous_choice public.vote_choice,test_data boolean)
language plpgsql security definer set search_path=public
as $$
declare actual_choice public.vote_choice; inserted_count integer;
begin
  if p_anonymous_user_id !~ '^anon_[0-9a-f-]{36}$' then raise exception 'Invalid anonymous ID'; end if;
  if not exists(select 1 from questions where id=p_question_id and active and real_votes_enabled and not optional_test_mode) then raise exception 'Question unavailable'; end if;
  insert into votes(anonymous_user_id,question_id,choice,is_test) values(p_anonymous_user_id,p_question_id,p_choice,false)
  on conflict(anonymous_user_id,question_id) do nothing;
  get diagnostics inserted_count = row_count;
  select v.choice into actual_choice from votes v where v.anonymous_user_id=p_anonymous_user_id and v.question_id=p_question_id;
  return query select count(*) filter(where v.choice='PRESS'),count(*) filter(where v.choice='WALK_AWAY'),count(*),case when inserted_count=0 then actual_choice else null end,false
    from votes v where v.question_id=p_question_id and not v.is_test;
end $$;

create or replace view public.question_admin_stats with (security_invoker=true) as
select q.*,count(v.id) filter(where not v.is_test) as total_votes,
  coalesce(100.0*count(v.id) filter(where v.choice='PRESS' and not v.is_test)/nullif(count(v.id) filter(where not v.is_test),0),50) as press_percentage
from public.questions q left join public.votes v on v.question_id=q.id group by q.id;

revoke all on function public.get_game_questions(integer) from public;
revoke all on function public.submit_vote(text,bigint,public.vote_choice) from public;
grant execute on function public.get_game_questions(integer) to anon,authenticated;
grant execute on function public.submit_vote(text,bigint,public.vote_choice) to anon,authenticated;
grant select on public.question_admin_stats to authenticated;

